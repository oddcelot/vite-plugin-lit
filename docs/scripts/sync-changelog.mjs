// Copies the root CHANGELOG.md into the docs content collection so it gets the
// full Starlight treatment (sidebar, table of contents, search, llms.txt, link
// validation). Starlight's docs loader only reads src/content/docs and requires
// a `title`, so a symlink to the hand-written file cannot work. The output is
// gitignored; the root file stays the single source of truth.
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../CHANGELOG.md');
const target = resolve(here, '../src/content/docs/reference/changelog.md');

const raw = await readFile(source, 'utf8');
// Drop the H1; Starlight renders the frontmatter title instead.
const body = raw.replace(/^# .*\n+/, '');

const frontmatter = [
  '---',
  'title: Changelog',
  'description: What shipped in each release of @oddsquad/vite-plugin-lit.',
  'sidebar:',
  '  order: 9',
  'editUrl: https://github.com/oddcelot/vite-plugin-lit/edit/main/CHANGELOG.md',
  'lastUpdated: false',
  '---',
  '',
  '<!-- Generated by docs/scripts/sync-changelog.mjs from the root CHANGELOG.md. Do not edit. -->',
  '',
  '',
].join('\n');

await mkdir(dirname(target), {recursive: true});
await writeFile(target, frontmatter + body);
console.log(`[sync-changelog] wrote ${target}`);
